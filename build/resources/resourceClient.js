export class ResourceClient {
    getMimeType(filename) {
        const ext = filename.toLowerCase().split(".").pop();
        switch (ext) {
            case "jpg":
            case "jpeg":
                return "image/jpeg";
            case "png":
                return "image/png";
            case "gif":
                return "image/gif";
            default:
                return "application/octet-stream";
        }
    }
}
